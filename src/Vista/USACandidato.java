    private static final String ARCHIVO_CANDIDATOS = "candidatos.dat";
    private ArrayList<Candidato> losCandidatos;

    /**
     * Creates new form USACandidato
     */
    public USACandidato() {
        losCandidatos = new ArrayList<>();
    }

    public static void main(String[] args) {
        new USACandidato().cargarArchivoCandidato();
    }

    public void agregarCandidato(Candidato candidato) {
        if (candidato == null) {
            throw new IllegalArgumentException("El candidato no puede ser null");
        }
        losCandidatos.add(candidato);
    }

    public void agregarCandidato() {
        throw new UnsupportedOperationException("Debe proporcionar un candidato");
    }

    public void guardarArchivoCandidato() {
        try (ObjectOutputStream salida = new ObjectOutputStream(
                new FileOutputStream(ARCHIVO_CANDIDATOS))) {
            salida.writeObject(losCandidatos);
        } catch (IOException ex) {
            throw new IllegalStateException("No se pudo guardar la información de candidatos", ex);
        }
    }

    @SuppressWarnings("unchecked")
    public void cargarArchivoCandidato() {
        try (ObjectInputStream entrada = new ObjectInputStream(
                new FileInputStream(ARCHIVO_CANDIDATOS))) {
            Object datos = entrada.readObject();
            if (!(datos instanceof ArrayList<?>)) {
                throw new IOException("El archivo no contiene una lista de candidatos");
            }
            ArrayList<?> lista = (ArrayList<?>) datos;
            ArrayList<Candidato> candidatos = new ArrayList<>();
            for (Object dato : lista) {
                if (!(dato instanceof Candidato)) {
                    throw new IOException("El archivo contiene un objeto inválido");
                }
                candidatos.add((Candidato) dato);
            }
            losCandidatos = candidatos;
        } catch (IOException | ClassNotFoundException ex) {
            throw new IllegalStateException("No se pudo cargar la información de candidatos", ex);
        }
    }

    public void limpiarCampos() {
        losCandidatos.clear();
    }

    public void salir() {
        losCandidatos.clear();
    }

    public String mostrarTodos(ArrayList<Candidato> datos) {
        if (datos == null) {
            throw new IllegalArgumentException("La lista de candidatos no puede ser null");
        }
        StringBuilder resultado = new StringBuilder();
        for (Candidato candidato : datos) {
            resultado.append(candidato.desplegarInformacionCompleta()).append(System.lineSeparator());
        }
        return resultado.toString();
    }

